-- TABLA GRUPOS
CREATE TABLE GRUPOS (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    fecha_creacion TIMESTAMP NOT NULL
);

-- TABLA ALUMNOS
CREATE TABLE ALUMNOS (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    apellido VARCHAR(100) NOT NULL,
    edad INT NOT NULL,
    fecha_creacion TIMESTAMP NOT NULL,
    grupo_id BIGINT,
    FOREIGN KEY (grupo_id) REFERENCES GRUPOS(id)
);

-- SECUENCIAS (opcional si quieres empezar desde 100)
DROP SEQUENCE IF EXISTS GRUPOS_SEQ;
CREATE SEQUENCE GRUPOS_SEQ START WITH 100 INCREMENT BY 1;

DROP SEQUENCE IF EXISTS ALUMNOS_SEQ;
CREATE SEQUENCE ALUMNOS_SEQ START WITH 100 INCREMENT BY 1;
